#!/bin/bash

# Перевіряємо, чи передано рівно два параметри
if [ "$#" -ne 2 ]; then
    echo "Помилка: потрібно передати рівно два параметри."
    echo "Використання: $0 <число1> <число2>"
    exit 1
fi

# Перевіряємо, чи є введені дані цілими числами (включно з від'ємними)
if ! [[ "$1" =~ ^-?[0-9]+$ ]] || ! [[ "$2" =~ ^-?[0-9]+$ ]]; then
    echo "Помилка: обидва параметри мають бути числами."
    exit 1
fi

if [ "$1" -gt "$2" ]; then
    echo "Перший параметр ($1) більший за другий ($2)."
    echo -e "\n--- Список псевдонімів (alias) вашої системи ---"
    
    # У неінтерактивних скриптах alias за замовчуванням вимкнені.
    # Вмикаємо їх і підтягуємо конфіг, щоб список не був пустим.
    shopt -s expand_aliases
    [ -f ~/.bashrc ] && source ~/.bashrc >/dev/null 2>&1
    alias
else
    echo "Перший параметр ($1) не більший за другий ($2)."
    
    # $0 містить ім'я або шлях, за яким було викликано скрипт
    SCRIPT_NAME="$0"
    
    # wc -c рахує байти файлу, tr прибирає можливі зайві пробіли у виводі
    SCRIPT_SIZE=$(wc -c < "$SCRIPT_NAME" | tr -d ' ')
    
    echo "Ім'я скрипта: $SCRIPT_NAME"
    echo "Розмір скрипта: $SCRIPT_SIZE байт"
fi
